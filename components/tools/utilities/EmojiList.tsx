export default function EmojiList() {
  const [selectedCategory, setSelectedCategory] = useState(0)
  const [searchQuery, setSearchQuery] = useState('')
  const [copied, setCopied] = useState<string | null>(null)

  // Filter emojis
  const filteredEmojis = emojiCategories[selectedCategory].emojis.filter(emoji => {
    if (!searchQuery) return true
    // Simple search (can be extended as needed)
    return emoji.includes(searchQuery)
  })

  // Copy to clipboard
  const handleCopy = async (emoji: string) => {
    // Track usage (called on actual use, only track on first use)
    if (copied === null) {
      trackUsage('emoji-list')
    }
    try {
      await copyToClipboard(emoji)
      setCopied(emoji)
      setTimeout(() => setCopied(null), 2000)
    } catch (err) {
      console.error('Failed to copy:', err)
    }
  }

  return (
    <div className="space-y-6">
      {/* Search box */}
      <div>
        <Input
          label="Search Emojis"
          value={searchQuery}
          onChange={(e) => setSearchQuery(e.target.value)}
          placeholder="Search emojis..."
        />
      </div>

      {/* Category selection */}
      <CategorySelector
        categories={emojiCategories}
        selectedIndex={selectedCategory}
        onSelect={setSelectedCategory}
      />

      {/* Emoji grid */}
      <div>
        <h2 className="text-xl font-semibold mb-4 text-text-primary">
          {emojiCategories[selectedCategory].name} ({filteredEmojis.length})
        </h2>
        <ClickableGrid
          items={filteredEmojis}
          renderItem={(emoji) => <span className="text-2xl">{emoji}</span>}
          onItemClick={handleCopy}
          selectedItem={copied}
          columns={12}
          itemClassName={(emoji, index, isSelected) => `
            p-3 bg-bg-card rounded-lg border-2 transition-all hover:scale-110 text-2xl
            ${isSelected
              ? 'border-success bg-success-bg'
              : 'border-border hover:border-accent'
            }
          `}
        />
        {copied && (
          <p className="mt-2 text-sm text-success text-center">
            ✓ Copied "{copied}" to clipboard!
          </p>
        )}
      </div>

      {/* Usage instructions */}
      <UsageInstructions
        items={[
          'Browse emojis by category',
          'Search for specific emojis',
          'Click on any emoji to copy it to clipboard',
          'Paste the emoji wherever you need it',
        ]}
      />
    </div>
  )
}

